/**
 * The NPC voices engine: watches one campaign room in Firestore and makes NPCs talk.
 *
 * Shared by two runners so they behave the same:
 * - 'online': the DM's browser (Show Time open) using free Groq / Gemini keys
 * - 'laptop': scripts/npc-voices on the DM's computer using Ollama
 *
 * Only one runner works at a time. The DM picks the brain in the chat settings; when the online
 * brain runs out of free requests it says so in npcAi/status and the laptop (if running) covers.
 *
 * Every visible mob can talk. Characters speak as one person; each copy of a creature on the map is
 * its own speaker ("Goblin B", see speakers.mjs). Speakers without a DM-written personality get one
 * generated by the model the first time they're needed, saved in npcAi/personalities (by speaker id)
 * so it stays the same all game. In the rest of this file `mobId` on a placement or job is that speaker id.
 *
 * Speakers remember: once a conversation with one has been quiet for a couple of minutes, the model folds
 * it into a few memory notes plus a feeling score per crawler (npcAi/memories, by speaker id), which go
 * into that speaker's prompt from then on. Characters keep their memory for good; a creature copy's memory
 * belongs to the episode it was made in.
 *
 * Plain JavaScript (no build step) so the Node script can import it directly.
 */
import { collection, doc, onSnapshot, setDoc, FieldPath } from 'firebase/firestore';
import {
  hasPersonality, distance, mentionsName, timeOfDay, hpWords,
  buildSystemPrompt, buildLinePrompt, buildShouldSpeakPrompt, buildSecretCheckPrompt,
  formatTranscript, isYes, cleanLine, parseGestureLine, hasGestureStyle, presetLine,
  rollPersonalityTraits, buildPersonalityPrompt, parsePersonality, defaultPersuasionDC, PERSONALITY_SYSTEM_PROMPT,
  MEMORY_SYSTEM_PROMPT, buildMemoryPrompt, parseMemory,
} from './brain.mjs';
import { mobLanguageIds, languageName, crawlerUnderstands, DEAD_LANGUAGE_ID, REAL_LANGUAGES } from '../languageList.mjs';
import { mapSpeakers, getMobKind } from './speakers.mjs';

export const DEFAULT_NPC_CONFIG = {
  nearDistance: 12,          // map-% units
  npcCooldownMs: 20_000,
  globalGapMs: 4_000,
  idleSilenceMs: 60_000,
  greetCooldownMs: 120_000,
  unloadAfterMs: 15 * 60_000,
  jobMaxAgeMs: 60_000,
  transcriptLines: 25,       // chat messages the speaker heard, sent with each prompt
  heartbeatMs: 15_000,
  memoryQuietMs: 120_000,    // a conversation this quiet is over and gets saved to memory
};

/** Which brain should be writing NPC lines right now. */
export function whoRuns(settings, status, now = Date.now()) {
  if ((settings?.brain ?? 'online') === 'laptop') return 'laptop';
  if ((status?.onlineOutUntil ?? 0) > now) return 'laptop';
  return 'online';
}

/** Thrown by an LLM adapter when it can't answer right now. `until` = when to try again. */
export class NpcLlmUnavailable extends Error {
  constructor(note, until) {
    super(note);
    this.note = note;
    this.until = until;
  }
}

const randomHex = () => Math.random().toString(16).slice(2, 8);

export class NpcRoom {
  /**
   * @param {object} opts
   * @param {import('firebase/firestore').Firestore} opts.db
   * @param {string} opts.roomId
   * @param {string} [opts.name]
   * @param {'online'|'laptop'} opts.role
   * @param {object} opts.llm  { generate({tier, system, user, maxTokens, temperature}) → {text, label}, prepare?(tier) → {label, note, busy}, idle?() }
   * @param {object} [opts.config]
   * @param {(...a: unknown[]) => void} [opts.log]
   * @param {(...a: unknown[]) => void} [opts.warn]
   * @param {(live: boolean) => void} [opts.onLiveChange]
   */
  constructor({ db, roomId, name, role, llm, config, log, warn, onLiveChange }) {
    this.db = db;
    this.id = roomId;
    this.name = name || roomId;
    this.role = role;
    this.llm = llm;
    this.config = { ...DEFAULT_NPC_CONFIG, ...(config || {}) };
    this.log = log || (() => {});
    this.warn = warn || (() => {});
    this.onLiveChange = onLiveChange || (() => {});
    this.path = `rooms/${roomId}`;
    this.live = false;
    this.gameLive = false;
    this.showtime = null;
    this.settings = {};
    this.status = {};
    this.secrets = {};
    this.state = {
      mobs: [], crawlers: [], episode: null, combat: null, clock: null,
      crawlerPlacements: [], runtimeMobPlacements: [], chat: [], lootBoxes: [], languages: [],
    };
    this.liveUnsubs = [];
    this.placementUnsubs = [];
    this.queue = [];
    this.working = false;
    this.lastNpcLineAt = 0;
    this.lastLineByNpc = new Map();
    this.lastGreet = new Map();        // `${crawlerId}:${mobId}` → ms
    this.lastActivityAt = Date.now();
    this.lastIdleMutterAt = 0;
    this.prevNear = new Set();         // `${crawlerId}:${mobId}` pairs near each other
    this.lastNpcByCrawler = new Map(); // crawlerId → mobId of the NPC they last talked with
    this.persuadeTries = new Map();    // `${crawlerId}:${mobId}` → { turn, at } of the last Persuasion try
    this.lastLanguageByMob = new Map(); // mobId → language it was last spoken to in (one it knows)
    this.activeModel = null;
    this.note = '';
    this.busy = false;
    this.unloaded = true;
    this.generated = {};               // speaker id → auto-generated personality (npcAi/personalities)
    this.generating = new Set();       // speaker ids with a personality being written right now
    this.personaFailedAt = new Map();  // speaker id → ms of the last failed attempt (retry after a while)
    this.memories = {};                // speaker id → memory (npcAi/memories)
    this.convos = new Map();           // speaker id → conversation not yet saved to memory

    const ref = (p) => doc(db, `${this.path}/${p}`);
    const fail = (what) => (e) => this.warn(`[${this.name}] ${what} listener`, e.message);
    this.baseUnsubs = [
      onSnapshot(ref('showtime-state/current'), (snap) => this.onShowtime(snap.exists() ? snap.data() : null), fail('showtime')),
      onSnapshot(ref('npcAi/settings'), (snap) => { this.settings = snap.exists() ? snap.data() : {}; this.evaluate(); this.publishStatus(); }, fail('settings')),
      onSnapshot(ref('npcAi/status'), (snap) => { this.status = snap.exists() ? snap.data() : {}; this.evaluate(); }, fail('status')),
      onSnapshot(ref('npcAi/secrets'), (snap) => this.onSecrets(snap.exists() ? snap.data() : {}), fail('secrets')),
      onSnapshot(ref('npcAi/personalities'), (snap) => { this.generated = snap.exists() ? snap.data() : {}; }, fail('personalities')),
      onSnapshot(ref('npcAi/memories'), (snap) => { this.memories = snap.exists() ? snap.data() : {}; }, fail('memories')),
    ];
    // Hand-offs between brains are time based (onlineOutUntil), so re-check regularly
    this.evalTimer = setInterval(() => this.evaluate(), 5_000);
  }

  get enabled() { return this.settings.enabled !== false; }

  dispose() {
    this.stop();
    clearInterval(this.evalTimer);
    this.baseUnsubs.forEach((u) => u());
  }

  // ── lifecycle ──

  onShowtime(data) {
    this.showtime = data;
    // Listen whenever the DM has an episode open in Show Time (the game clock does not need to be started)
    this.gameLive = !!data && data.isActive === true && !!data.episodeId;
    this.evaluate();
    if (this.live) this.syncEpisode(); // map or episode may have changed
  }

  /** Start or stop depending on whether the game is live and this brain is the one that should talk. */
  evaluate() {
    const want = this.gameLive && this.enabled && whoRuns(this.settings, this.status) === this.role;
    if (want && !this.live) this.start();
    else if (!want && this.live) this.stop();
  }

  syncEpisode() {
    this.state.episode = (this.state.episodes || []).find((e) => e.id === this.showtime?.episodeId) || null;
    this.watchPlacements();
  }

  start() {
    const { db } = this;
    this.live = true;
    this.startedAt = Date.now();
    this.lastActivityAt = Date.now();
    this.log(`[${this.name}] Game started: NPC voices listening (${this.role})`);
    const sub = (ref, onData) => onSnapshot(ref, onData, (e) => this.warn(`[${this.name}]`, e.message));
    this.liveUnsubs = [
      sub(collection(db, `${this.path}/mobs`), (s) => { this.state.mobs = s.docs.map((d) => ({ ...d.data(), id: d.id })); }),
      sub(collection(db, `${this.path}/crawlers`), (s) => this.onCrawlers(s.docs.map((d) => ({ ...d.data(), id: d.id })))),
      sub(collection(db, `${this.path}/episodes`), (s) => {
        this.state.episodes = s.docs.map((d) => ({ ...d.data(), id: d.id }));
        this.syncEpisode();
      }),
      sub(doc(db, `${this.path}/combatState/current`), (s) => this.onCombat(s.exists() ? s.data() : null)),
      sub(doc(db, `${this.path}/gameClock/current`), (s) => { this.state.clock = s.exists() ? s.data() : null; }),
      sub(collection(db, `${this.path}/lootBoxes`), (s) => this.onLootBoxes(s.docs.map((d) => ({ ...d.data(), id: d.id })))),
      sub(collection(db, `${this.path}/chatMessages`), (s) => this.onChat(s)),
      sub(collection(db, `${this.path}/diceRolls`), (s) => this.onDiceRolls(s)),
      sub(doc(db, `${this.path}/noncombatTurns/current`), (s) => { this.state.noncombatTurn = s.exists() ? s.data() : null; }),
      sub(collection(db, `${this.path}/languages`), (s) => { this.state.languages = s.docs.map((d) => ({ ...d.data(), id: d.id })); }),
    ];
    this.watchPlacements();
    this.heartbeat = setInterval(() => this.publishStatus(), this.config.heartbeatMs);
    this.tick = setInterval(() => this.onTick(), 5_000);
    this.onLiveChange(true);
    this.publishStatus();
  }

  stop() {
    if (!this.live) return;
    this.live = false;
    this.log(`[${this.name}] NPC voices idle (${this.role})`);
    this.liveUnsubs.forEach((u) => u());
    this.placementUnsubs.forEach((u) => u());
    this.liveUnsubs = [];
    this.placementUnsubs = [];
    clearInterval(this.heartbeat);
    clearInterval(this.tick);
    this.queue = [];
    this.state.chat = [];
    this.state.episode = null;
    this.placementKey = null;
    this.chatPrimed = this.crawlersPrimed = this.combatPrimed = this.lootPrimed = this.primedPlacements = this.rollsPrimed = false;
    this.prevNear = new Set();
    // Don't clear the other brain's heartbeat when handing over to it
    if ((this.status.runner ?? this.role) === this.role) {
      this.writeStatus({ heartbeatAt: 0, thinking: null, activeModel: null });
    }
    if (this.llm.idle && !this.unloaded) { this.unloaded = true; Promise.resolve(this.llm.idle()).catch(() => {}); }
    this.onLiveChange(false);
  }

  get currentMapId() {
    const ep = this.state.episode;
    const idx = this.showtime?.currentMapIndex ?? 0;
    return ep?.mapIds?.[idx] ?? null;
  }

  /** Follow token positions for the episode's current map (re-run when the map changes). */
  watchPlacements() {
    const epId = this.showtime?.episodeId;
    const mapId = this.currentMapId;
    const key = epId && mapId !== null ? `${epId}-${mapId}` : null;
    if (key === this.placementKey) return;
    this.placementKey = key;
    this.placementUnsubs.forEach((u) => u());
    this.placementUnsubs = [];
    this.state.crawlerPlacements = [];
    this.state.runtimeMobPlacements = [];
    this.prevNear = new Set();
    this.primedPlacements = false;
    if (!key) return; // episode not loaded yet; the episodes listener calls us again
    const fail = (e) => this.warn(`[${this.name}]`, e.message);
    this.placementUnsubs = [
      onSnapshot(doc(this.db, `${this.path}/crawler-placements/${key}`), (s) => this.onCrawlerPlacements(s.exists() ? (s.data().placements || []) : []), fail),
      onSnapshot(doc(this.db, `${this.path}/runtime-mob-placements/${key}`), (s) => { this.state.runtimeMobPlacements = s.exists() ? (s.data().placements || []) : []; }, fail),
    ];
  }

  // ── scene helpers ──

  /** Tokens on the current map that can talk, as { ...placement, mobId: speaker id, sourceMobId, mob }. */
  npcPlacements() {
    const mapId = this.currentMapId;
    const ep = this.state.episode;
    if (!ep || mapId === null) return [];
    const episodePlacements = (ep.mobPlacements || []).filter((p) => p.mapId === mapId || (!p.mapId && ep.mapIds?.[0] === mapId));
    const runtime = this.state.runtimeMobPlacements.filter((p) => p.mapId === mapId);
    const muted = new Set(this.settings.mutedMobIds || []);
    return mapSpeakers([...episodePlacements, ...runtime], this.state.mobs, [...(ep.mobPlacements || []), ...runtime])
      // Unencountered (hidden) mobs still talk: their token is on the map
      .filter((s) => !s.mob.silent && !muted.has(s.id) && !muted.has(s.mob.id))
      .map((s) => {
        const mob = this.speakerMob(s);
        // A token at 0 HP is a corpse: it speaks Dead, so it only answers someone using Speak with Dead
        const dead = this.isDown(s.placement);
        return { ...s.placement, mobId: s.id, sourceMobId: s.mob.id, dead, mob: dead ? { ...mob, languages: [DEAD_LANGUAGE_ID, ...mobLanguageIds(mob)] } : mob };
      });
  }

  /** Whether a mob token is at 0 HP: its combat HP during a fight, else the HP saved on the token. */
  isDown(placement) {
    let hp = placement.currentHP;
    const combat = this.state.combat;
    if (combat?.active && combat.phase !== 'ended') {
      // Same combat ids the app uses: "mobId:index" across all placements when there are several copies
      const all = [...(this.state.episode?.mobPlacements || []), ...this.state.runtimeMobPlacements];
      const copies = all.filter((p) => p.mobId === placement.mobId).length;
      const combatId = copies > 1 ? `${placement.mobId}:${all.indexOf(placement)}` : placement.mobId;
      const combatant = (combat.combatants || []).find((c) => c.id === combatId);
      if (combatant?.currentHP !== undefined) hp = combatant.currentHP;
    }
    return typeof hp === 'number' && hp <= 0;
  }

  /** The speaker with the personality it talks with: the DM's card, else the generated one (may be empty until written). */
  speakerMob(speaker) {
    const species = speaker.mob.speciesId ? this.state.mobs.find((m) => m.id === speaker.mob.speciesId) : null;
    const mob = { ...speaker.mob, id: speaker.id, name: speaker.name, sourceMobId: speaker.mob.id, ...(species ? { speciesName: species.name } : {}) };
    if (hasPersonality(mob)) return mob;
    const generated = this.generated[speaker.id];
    return generated ? { ...mob, personality: generated, personalityGenerated: true } : mob;
  }

  /** A speaker on the current map by id, or null if it isn't there (or is hidden or muted). */
  mobById(speakerId) {
    return this.npcPlacements().find((n) => n.mobId === speakerId)?.mob ?? null;
  }

  /** What a speaker remembers. A creature copy's memory only counts in the episode it was made in. */
  memoryFor(mob) {
    const memory = this.memories[mob.id];
    if (!memory) return null;
    if (memory.episodeId && memory.episodeId !== this.showtime?.episodeId) return null;
    return memory;
  }

  /** A crawler is talking with a speaker: remember the conversation so it can be saved once it ends. */
  noteConvo(mob, crawlerId) {
    const now = Date.now();
    const convo = this.convos.get(mob.id) ?? {
      since: now, crawlerIds: new Set(), name: mob.name, episodeId: this.showtime?.episodeId,
      creature: getMobKind(mob) === 'creature',
    };
    convo.lastAt = now;
    if (crawlerId) convo.crawlerIds.add(crawlerId);
    this.convos.set(mob.id, convo);
  }

  needsPersonality(mob) {
    return !hasPersonality(mob) && !this.generating.has(mob.id)
      && Date.now() - (this.personaFailedAt.get(mob.id) ?? 0) > 10 * 60_000;
  }

  /** Make sure a mob has a personality before it speaks, writing one with the model if needed. */
  async ensurePersonality(placement, tier) {
    const mob = this.mobById(placement.mobId);
    if (!mob || !this.needsPersonality(mob)) return mob;
    this.generating.add(mob.id);
    try {
      const traits = rollPersonalityTraits();
      const items = placement.inventoryOverride ?? mob.defaultInventory ?? [];
      const prompt = buildPersonalityPrompt({ mob, items, gold: mob.defaultGold, traits, episodeName: this.state.episode?.name });
      const raw = await this.ask(tier, PERSONALITY_SYSTEM_PROMPT, prompt, { maxTokens: 400, temperature: 1, json: true });
      const personality = parsePersonality(raw);
      if (!personality) {
        this.personaFailedAt.set(mob.id, Date.now());
        this.warn(`[${this.name}] Couldn't read a personality for ${mob.name}; it will talk with a plain voice for now`);
        return mob;
      }
      if (personality.secret) personality.persuasionDC = defaultPersuasionDC(mob);
      const entry = { ...personality, traits, generatedAt: Date.now() };
      this.generated = { ...this.generated, [mob.id]: entry };
      await setDoc(doc(this.db, `${this.path}/npcAi/personalities`), { [mob.id]: entry }, { merge: true });
      this.log(`[${this.name}] Made a personality for ${mob.name} (${traits.temperament}; ${traits.quirk})`);
      return this.mobById(mob.id);
    } catch (err) {
      if (!(err instanceof NpcLlmUnavailable)) this.personaFailedAt.set(mob.id, Date.now());
      throw err;
    } finally {
      this.generating.delete(mob.id);
    }
  }

  crawlerPlacementsOnMap() {
    const mapId = this.currentMapId;
    return this.state.crawlerPlacements.filter((p) => p.mapId === mapId);
  }

  /** The NPC's placement closest to a point (NPCs can be placed more than once). */
  placementFor(mobId, near) {
    const places = this.npcPlacements().filter((p) => p.mobId === mobId);
    if (!places.length) return null;
    if (!near) return places[0];
    return places.reduce((best, p) => (distance(p, near) < distance(best, near) ? p : best));
  }

  nearPairs() {
    const pairs = [];
    for (const c of this.crawlerPlacementsOnMap()) {
      for (const n of this.npcPlacements()) {
        const d = distance(c, n);
        if (d <= this.config.nearDistance) pairs.push({ crawlerId: c.crawlerId, mobId: n.mobId, d, npc: n, crawler: c });
      }
    }
    return pairs;
  }

  scene(npcPlacement) {
    const crawlers = this.state.crawlers;
    const nearby = [];
    const farther = [];
    for (const p of this.crawlerPlacementsOnMap()) {
      const c = crawlers.find((x) => x.id === p.crawlerId);
      if (!c) continue;
      (npcPlacement && distance(p, npcPlacement) <= this.config.nearDistance ? nearby : farther).push(c);
    }
    const combat = this.state.combat;
    return {
      episodeName: this.state.episode?.name,
      episodeDescription: (this.state.episode?.description || '').slice(0, 200),
      timeOfDay: timeOfDay(this.state.clock?.gameTime),
      inCombat: !!combat?.active && combat.phase !== 'ended',
      nearby,
      farther,
    };
  }

  /**
   * Could this speaker have heard a chat message? Its own lines, players' messages sent while it was in
   * talking range (the app records who was), the DM's narration unless aimed at someone else, and other
   * NPCs' lines spoken on this map close by. Nothing from other maps or out of earshot.
   */
  heardBy(m, speakerId, placement) {
    if (m.authorType === 'npc') {
      if (m.authorId === speakerId) return true;
      return !!placement && m.mapId === this.currentMapId && typeof m.x === 'number' && typeof m.y === 'number'
        && distance(m, placement) <= this.config.nearDistance;
    }
    const to = m.toMobIds || [];
    if (m.authorType === 'dm') return !to.length || to.includes(speakerId);
    if (to.includes(speakerId)) return true;
    return Array.isArray(m.nearMobIds) ? m.nearMobIds.includes(speakerId) : true;
  }

  /**
   * The recent chat a speaker heard in the current episode (see heardBy). Lines in languages it
   * doesn't know stay unreadable to it.
   */
  transcript(mob, placement) {
    const epId = this.showtime?.episodeId;
    return this.formatFor(mob, this.state.chat
      .filter((m) => !m.translationOf && (!m.episodeId || m.episodeId === epId) && this.heardBy(m, mob.id, placement))
      .slice(-this.config.transcriptLines));
  }

  formatFor(mob, lines) {
    return formatTranscript(lines, (lang) => this.mobKnows(mob, lang), (lang) => this.languageName(lang));
  }

  languageName(id) {
    return languageName(id, this.state.languages);
  }

  /** Corpses (mobs that speak Dead, including any token at 0 HP) stay silent unless someone talks to them in Dead. */
  isCorpse(mob) {
    return !!mob && mobLanguageIds(mob).includes(DEAD_LANGUAGE_ID);
  }

  /** Whether any crawler in the campaign follows a language (their own, from a spell or an item). */
  partyUnderstands(languageId) {
    return this.state.crawlers.some((c) => crawlerUnderstands(c, languageId));
  }

  /**
   * The language a speaker answers in: the one it was spoken to in (if it knows it), else the last one
   * it was addressed in, else its native tongue. Corpses always answer in Dead.
   */
  replyLanguage(mob, heard) {
    const known = mobLanguageIds(mob);
    if (heard && known.includes(heard)) this.lastLanguageByMob.set(mob.id, heard);
    const lastHeard = this.lastLanguageByMob.get(mob.id);
    return this.isCorpse(mob) ? DEAD_LANGUAGE_ID : lastHeard && known.includes(lastHeard) ? lastHeard : known[0];
  }

  mobKnows(mob, languageId) {
    return !languageId || mobLanguageIds(mob).includes(languageId);
  }

  /**
   * What a mob hears when someone talks: the words if it knows the language, else just that it
   * couldn't follow. `heard` is the language to answer in (only when it understood).
   */
  hearing(mob, m, words) {
    if (this.mobKnows(mob, m.language)) return { trigger: `${words}: "${m.text}"`, heard: m.language };
    return { trigger: `${words} in ${this.languageName(m.language)}, a language you don't understand.`, heard: undefined };
  }

  // ── events ──

  onChat(snapshot) {
    const all = snapshot.docs.map((d) => ({ ...d.data(), id: d.id })).sort((a, b) => (a.createdAt ?? 0) - (b.createdAt ?? 0));
    this.state.chat = all.slice(-150);
    // On the first snapshot, skip old history but pick up anything said in the last few seconds,
    // so a message that arrived while the other brain was handing over still gets an answer.
    const priming = !this.chatPrimed;
    this.chatPrimed = true;
    for (const change of snapshot.docChanges()) {
      if (change.type !== 'added') continue;
      const m = { ...change.doc.data(), id: change.doc.id };
      if (priming && (m.createdAt ?? 0) < Date.now() - 15_000) continue;
      if (m.authorType === 'npc' || m.translationOf) continue;
      if (m.episodeId && m.episodeId !== this.showtime?.episodeId) continue;
      if ((m.createdAt ?? 0) < Date.now() - 120_000) continue;
      this.lastActivityAt = Date.now();
      this.handlePlayerMessage(m);
    }
  }

  handlePlayerMessage(m) {
    const npcs = this.npcPlacements();
    if (!npcs.length) return;
    const uniqueMobs = [...new Map(npcs.map((n) => [n.mobId, n.mob])).values()];
    const tagged = new Set(m.toMobIds || []);
    const speakerSpot = m.authorType === 'crawler' ? this.crawlerPlacementsOnMap().find((p) => p.crawlerId === m.authorId) : null;
    let named = uniqueMobs.filter((mob) => tagged.has(mob.id) || mentionsName(m.text, mob.name));
    // "Hey goblin" with several goblins around: only the closest one answers (tagging picks a specific one)
    const byCreature = new Map();
    for (const mob of named) {
      if (tagged.has(mob.id) || mob.id === mob.sourceMobId) continue;
      const spot = npcs.find((n) => n.mobId === mob.id);
      const best = byCreature.get(mob.sourceMobId);
      const d = speakerSpot && spot ? distance(spot, speakerSpot) : 0;
      if (!best || d < best.d) byCreature.set(mob.sourceMobId, { id: mob.id, d });
    }
    named = named.filter((mob) => tagged.has(mob.id) || mob.id === mob.sourceMobId || byCreature.get(mob.sourceMobId)?.id === mob.id);
    // Players can only talk to mobs within talking range (worked out in feet by their app when they sent it)
    const inRange = m.authorType === 'crawler' && Array.isArray(m.nearMobIds) ? new Set(m.nearMobIds) : null;
    if (inRange) named = named.filter((mob) => inRange.has(mob.id));
    const nearSpeaker = speakerSpot
      ? npcs.filter((n) => (inRange ? inRange.has(n.mobId) : distance(n, speakerSpot) <= this.config.nearDistance))
        .sort((a, b) => distance(a, speakerSpot) - distance(b, speakerSpot))
      : [];

    // Secret checks for NPCs being talked to or standing next to the speaker
    const involved = new Map([...named.map((mob) => [mob.id, mob]), ...nearSpeaker.map((n) => [n.mobId, n.mob])]);
    for (const mob of involved.values()) {
      const p = mob.personality || {};
      const state = this.secrets[mob.id]?.state ?? 'locked';
      if (p.secret && p.revealWhen && state === 'locked' && this.mobKnows(mob, m.language)) this.enqueue({ kind: 'secret-check', mobId: mob.id, message: m });
    }

    if (m.authorType === 'crawler') {
      const talkedTo = named[0]?.id ?? nearSpeaker[0]?.mobId;
      if (talkedTo) this.lastNpcByCrawler.set(m.authorId, talkedTo);
      const listeners = named.length ? named.slice(0, 2) : nearSpeaker.slice(0, 1).map((n) => n.mob);
      for (const mob of listeners) this.noteConvo(mob, m.authorId);
    }

    if (named.length) {
      for (const mob of named.slice(0, 2)) {
        this.enqueue({ kind: 'line', mobId: mob.id, direct: true, fromDm: m.authorType === 'dm', near: speakerSpot, ...this.hearing(mob, m, `${m.authorName} spoke to you`) });
      }
    } else if (nearSpeaker.length) {
      const n = nearSpeaker[0];
      this.enqueue({ kind: 'line', mobId: n.mobId, gated: true, near: speakerSpot, ...this.hearing(n.mob, m, `${m.authorName} said this right next to you`) });
    }
  }

  onSecrets(data) {
    const prev = this.secrets;
    this.secrets = data;
    if (!this.secretsPrimed) { this.secretsPrimed = true; return; }
    // When the DM unlocks a secret, that NPC speaks up with it right away.
    for (const [mobId, entry] of Object.entries(data)) {
      if (entry?.state === 'unlocked' && prev[mobId]?.state !== 'unlocked') {
        this.lastActivityAt = Date.now();
        this.enqueue({ kind: 'line', mobId, direct: true, trigger: 'You have just decided to tell the party your secret. Tell them now.' });
      }
    }
  }

  onDiceRolls(snapshot) {
    if (!this.rollsPrimed) { this.rollsPrimed = true; return; }
    for (const change of snapshot.docChanges()) {
      if (change.type !== 'added') continue;
      const roll = change.doc.data();
      if (roll.statRoll?.stat !== 'Persuasion' || !roll.crawlerId) continue;
      if ((roll.timestamp ?? 0) < Date.now() - 120_000) continue;
      this.lastActivityAt = Date.now();
      this.handlePersuasion(roll);
    }
  }

  /** A Persuasion roll counts against the NPC next to the crawler, else the NPC they last talked with. */
  handlePersuasion(roll) {
    const npcs = this.npcPlacements();
    const spot = this.crawlerPlacementsOnMap().find((p) => p.crawlerId === roll.crawlerId);
    const nearest = spot
      ? npcs.filter((n) => distance(n, spot) <= this.config.nearDistance).sort((a, b) => distance(a, spot) - distance(b, spot))[0]
      : null;
    const mobId = nearest?.mobId ?? this.lastNpcByCrawler.get(roll.crawlerId);
    const target = npcs.find((n) => n.mobId === mobId);
    if (!target) return;
    const mob = target.mob;
    const p = mob.personality || {};
    const dc = Number(p.persuasionDC);
    const state = this.secrets[mob.id]?.state ?? 'locked';
    if (!p.secret || !dc || state !== 'locked') return;

    // One try per crawler per NPC each noncombat turn (or every 10 minutes when turns aren't running)
    const key = `${roll.crawlerId}:${mob.id}`;
    const turn = this.state.noncombatTurn?.turnNumber ?? null;
    const prev = this.persuadeTries.get(key);
    if (prev && (turn !== null ? prev.turn === turn : Date.now() - prev.at < 10 * 60_000)) return;
    this.persuadeTries.set(key, { turn, at: Date.now() });

    const name = roll.crawlerName || 'A crawler';
    const near = spot ?? undefined;
    if (roll.total >= dc) {
      this.log(`[${this.name}] ${name} persuaded ${mob.name} (${roll.total} vs DC ${dc}); asking the DM`);
      setDoc(doc(this.db, `${this.path}/npcAi/secrets`), {
        [mob.id]: { state: 'pending', reason: `${name} rolled Persuasion ${roll.total} vs DC ${dc}.`, at: Date.now() },
      }, { merge: true }).catch((e) => this.warn(`[${this.name}] secret write failed:`, e.message));
      this.enqueue({ kind: 'line', mobId: mob.id, direct: true, near, trigger: `${name} just made a very convincing case for you to tell them your secret. You are wavering but haven't given in yet.` });
    } else {
      this.log(`[${this.name}] ${name} failed to persuade ${mob.name} (${roll.total} vs DC ${dc})`);
      this.enqueue({ kind: 'line', mobId: mob.id, direct: true, near, trigger: `${name} just tried to talk you into telling your secret, but it didn't work on you. Brush them off.` });
    }
  }

  onCrawlerPlacements(placements) {
    this.state.crawlerPlacements = placements;
    const nowNear = new Set();
    for (const pair of this.nearPairs()) {
      const key = `${pair.crawlerId}:${pair.mobId}`;
      nowNear.add(key);
      if (this.prevNear.has(key) || !this.primedPlacements) continue;
      if (Date.now() - (this.lastGreet.get(key) ?? 0) < this.config.greetCooldownMs) continue;
      this.lastGreet.set(key, Date.now());
      this.lastActivityAt = Date.now();
      const crawler = this.state.crawlers.find((c) => c.id === pair.crawlerId);
      this.enqueue({ kind: 'line', mobId: pair.mobId, near: pair.crawler, trigger: `${crawler?.name ?? 'A crawler'} just walked up to you.` });
    }
    this.prevNear = nowNear;
    this.primedPlacements = true;
  }

  onCrawlers(list) {
    const prev = new Map(this.state.crawlers.map((c) => [c.id, c]));
    this.state.crawlers = list;
    if (!this.crawlersPrimed) { this.crawlersPrimed = true; return; }
    for (const c of list) {
      const before = prev.get(c.id);
      if (!before || !c.maxHP) continue;
      if (before.hp / c.maxHP >= 0.3 && c.hp / c.maxHP < 0.3) {
        this.lastActivityAt = Date.now();
        this.reactNear(c.id, `${c.name} was just ${hpWords(c.hp, c.maxHP)}.`);
      }
    }
  }

  onCombat(data) {
    const prev = this.state.combat;
    this.state.combat = data;
    if (!this.combatPrimed) { this.combatPrimed = true; return; }
    const activeNow = !!data?.active && data.phase !== 'ended';
    const activeBefore = !!prev?.active && prev.phase !== 'ended';
    if (activeNow && !activeBefore) {
      this.lastActivityAt = Date.now();
      const foes = (data.combatants || []).filter((c) => c.type === 'mob').map((c) => c.name);
      this.reactAll(`A fight just broke out${foes.length ? ` against ${[...new Set(foes)].join(', ')}` : ''}.`, true);
    }
    if (activeNow && prev?.combatants) {
      for (const c of data.combatants || []) {
        if (c.type !== 'mob') continue;
        const before = prev.combatants.find((x) => x.id === c.id);
        if (before && (before.currentHP ?? 1) > 0 && (c.currentHP ?? 1) <= 0) {
          this.lastActivityAt = Date.now();
          this.reactAll(`${c.name} was just killed.`, true);
        }
      }
    }
  }

  onLootBoxes(list) {
    const prev = new Map(this.state.lootBoxes.map((b) => [b.id, b]));
    this.state.lootBoxes = list;
    if (!this.lootPrimed) { this.lootPrimed = true; return; }
    for (const b of list) {
      const before = prev.get(b.id);
      if (before && before.locked && !b.locked && b.episodeId === this.showtime?.episodeId) {
        const crawler = this.state.crawlers.find((c) => c.id === b.crawlerId);
        this.lastActivityAt = Date.now();
        this.reactNear(b.crawlerId, `${crawler?.name ?? 'A crawler'} just opened a ${b.tier} loot box: ${b.name}.`);
      }
    }
  }

  /** NPCs standing near a crawler react to something that happened to them. */
  reactNear(crawlerId, trigger) {
    const spot = this.crawlerPlacementsOnMap().find((p) => p.crawlerId === crawlerId);
    if (!spot) return;
    const near = this.npcPlacements().filter((n) => distance(n, spot) <= this.config.nearDistance);
    if (near.length) this.enqueue({ kind: 'line', mobId: near[0].mobId, near: spot, trigger });
  }

  /** The NPC with crawlers closest to it reacts to a big event. */
  reactAll(trigger, gated) {
    const pairs = this.nearPairs().sort((a, b) => a.d - b.d);
    const pick = pairs[0]?.npc ?? this.npcPlacements()[0];
    if (pick) this.enqueue({ kind: 'line', mobId: pick.mobId, gated: gated && !pairs.length, near: pairs[0]?.crawler, trigger });
  }

  onTick() {
    if (!this.live) return;
    const now = Date.now();
    if (!this.unloaded && now - this.lastActivityAt > this.config.unloadAfterMs && !this.working) {
      this.unloaded = true;
      this.activeModel = null;
      if (this.llm.idle) Promise.resolve(this.llm.idle()).catch(() => {});
      this.publishStatus();
      return;
    }
    // Conversations that have gone quiet get saved to the speaker's memory
    for (const [mobId, convo] of this.convos) {
      if (now - convo.lastAt < this.config.memoryQuietMs || this.queue.some((j) => j.kind === 'memory' && j.mobId === mobId)) continue;
      this.enqueue({ kind: 'memory', mobId });
    }
    // While things are quiet, write personalities ahead of time for mobs on the map that lack one
    if (!this.queue.length && !this.working && now - this.lastActivityAt < this.config.unloadAfterMs) {
      const missing = this.npcPlacements().find((n) => this.needsPersonality(n.mob));
      if (missing) { this.enqueue({ kind: 'persona', mobId: missing.mobId }); return; }
    }
    const quietSince = Math.max(this.lastActivityAt, this.lastNpcLineAt, this.lastIdleMutterAt);
    if (now - quietSince < this.config.idleSilenceMs || this.queue.length || this.working) return;
    if (now - this.lastActivityAt > this.config.unloadAfterMs) return; // nobody around: stay asleep
    const pairs = this.nearPairs();
    if (!pairs.length) return;
    const pair = pairs[Math.floor(Math.random() * pairs.length)];
    this.lastIdleMutterAt = now;
    this.enqueue({ kind: 'line', mobId: pair.mobId, gated: true, near: pair.crawler, trigger: 'It has been quiet for a while. The crawlers are standing around near you.' });
  }

  // ── work queue ──

  enqueue(job) {
    if (!this.live || !this.enabled || this.settings.mutedAll) return;
    job.createdAt = Date.now();
    if (job.kind === 'line') {
      const mob = this.npcPlacements().find((n) => n.mobId === job.mobId)?.mob;
      // The DM can always get a corpse to answer by tagging it
      if (this.isCorpse(mob) && job.heard !== DEAD_LANGUAGE_ID && !(job.fromDm && job.direct)) return;
      const existing = this.queue.findIndex((j) => j.kind === 'line' && j.mobId === job.mobId);
      if (existing >= 0) {
        if (job.direct || !this.queue[existing].direct) this.queue[existing] = job;
        return;
      }
    }
    if (job.kind === 'secret-check') this.queue.unshift(job); // cheap and decides whether to prompt the DM
    else this.queue.push(job);
    this.drain();
  }

  async drain() {
    if (this.working) return;
    this.working = true;
    try {
      while (this.queue.length && this.live) {
        const job = this.queue.shift();
        if (job.kind !== 'memory' && Date.now() - job.createdAt > this.config.jobMaxAgeMs) continue;
        try {
          if (job.kind === 'secret-check') await this.runSecretCheck(job);
          else if (job.kind === 'persona') await this.runPersona(job);
          else if (job.kind === 'memory') await this.runMemory(job);
          else await this.runLine(job);
        } catch (err) {
          if (err instanceof NpcLlmUnavailable) {
            await this.onUnavailable(err);
          } else {
            this.warn(`[${this.name}] ${job.kind} failed:`, err.message);
            this.note = this.role === 'laptop'
              ? 'NPC voices hit an error; check the log on the DM computer'
              : 'NPC voices hit an error; check the browser console';
            this.publishStatus();
          }
        }
      }
    } finally {
      this.working = false;
    }
  }

  /** The model can't answer: note why, and for the online brain, hand over to the laptop until it can. */
  async onUnavailable(err) {
    this.warn(`[${this.name}] ${err.note}`);
    this.note = err.note;
    if (this.role === 'online' && err.until) {
      this.queue = [];
      await this.writeStatus({ onlineOutUntil: err.until, note: err.note, thinking: null });
      this.status = { ...this.status, onlineOutUntil: err.until };
      this.evaluate();
    } else {
      this.publishStatus();
    }
  }

  /** New keys or settings for the online brain: stop waiting out the last failure and try again now. */
  async retryOnline() {
    if (this.role !== 'online' || !((this.status.onlineOutUntil ?? 0) > Date.now())) return;
    this.status = { ...this.status, onlineOutUntil: 0 };
    await this.writeStatus({ onlineOutUntil: 0, note: '' });
    this.evaluate();
  }

  /** Ask the adapter which model it will use; updates the status shown in the app. */
  async prepare() {
    const tier = this.settings.model === 'fast' ? 'fast' : 'quality';
    const info = this.llm.prepare ? await this.llm.prepare(tier) : { label: null, note: '' };
    const label = info.label ?? null;
    const note = info.note || '';
    const changed = label !== this.activeModel || note !== this.note || !!info.busy !== this.busy;
    this.activeModel = label;
    this.note = note;
    this.busy = !!info.busy;
    if (changed) this.publishStatus();
    if (info.busy) return null;
    this.unloaded = false;
    return tier;
  }

  async ask(tier, system, user, opts) {
    const { text, label } = await this.llm.generate({ tier, system, user, ...opts });
    if (label && label !== this.activeModel) { this.activeModel = label; this.publishStatus(); }
    return text;
  }

  async runPersona(job) {
    const placement = this.placementFor(job.mobId);
    if (!placement || !this.needsPersonality(placement.mob)) return;
    const tier = await this.prepare();
    if (tier) await this.ensurePersonality(placement, tier);
  }

  /** Fold a finished conversation into the speaker's memory. */
  async runMemory(job) {
    const convo = this.convos.get(job.mobId);
    if (!convo || Date.now() - convo.lastAt < this.config.memoryQuietMs) return;
    const placement = this.placementFor(job.mobId);
    const lines = this.state.chat.filter((m) => (m.createdAt ?? 0) >= convo.since - 5_000
      && !m.translationOf && (!m.episodeId || m.episodeId === convo.episodeId)
      && this.heardBy(m, job.mobId, placement));
    if (!lines.some((m) => m.authorType === 'npc' && m.authorId === job.mobId)) { this.convos.delete(job.mobId); return; }
    const tier = await this.prepare();
    if (!tier) return; // try again on a later tick
    this.convos.delete(job.mobId);
    const mob = this.mobById(job.mobId) ?? { id: job.mobId, name: convo.name };
    const prev = convo.creature && this.memories[job.mobId]?.episodeId !== convo.episodeId ? null : this.memories[job.mobId];
    const crawlers = this.state.crawlers.filter((c) => convo.crawlerIds.has(c.id));
    let raw;
    try {
      raw = await this.ask(tier, MEMORY_SYSTEM_PROMPT, buildMemoryPrompt({
        mob, memory: prev, transcript: this.formatFor(mob, lines.slice(-30)), crawlerNames: crawlers.map((c) => c.name),
      }), { maxTokens: 400, temperature: 0.3, json: true });
    } catch (err) {
      if (err instanceof NpcLlmUnavailable) this.convos.set(job.mobId, convo); // save it once the model is back
      throw err;
    }
    const update = parseMemory(raw, crawlers, prev);
    if (!update) { this.warn(`[${this.name}] Couldn't read a memory update for ${convo.name}`); return; }
    const entry = { ...update, name: convo.name, updatedAt: Date.now(), ...(convo.creature ? { episodeId: convo.episodeId } : {}) };
    this.memories = { ...this.memories, [job.mobId]: entry };
    // Replace this speaker's entry as a whole (merge would keep feelings from an old episode's copy)
    await setDoc(doc(this.db, `${this.path}/npcAi/memories`), { [job.mobId]: entry }, { mergeFields: [new FieldPath(job.mobId)] });
    this.log(`[${this.name}] ${convo.name} will remember: ${update.notes.join(' | ')}`);
  }

  async runSecretCheck(job) {
    const mob = this.mobById(job.mobId);
    const p = mob?.personality;
    if (!p?.secret || !p.revealWhen) return;
    if ((this.secrets[mob.id]?.state ?? 'locked') !== 'locked') return;
    const tier = await this.prepare();
    if (!tier) return;
    const reply = await this.ask(tier, null, buildSecretCheckPrompt({
      condition: p.revealWhen, speaker: job.message.authorName, text: job.message.text, transcript: this.transcript(mob, this.placementFor(mob.id)),
    }), { maxTokens: 4, temperature: 0 });
    if (!isYes(reply)) return;
    this.log(`[${this.name}] Reveal condition met for ${mob.name}; asking the DM`);
    await setDoc(doc(this.db, `${this.path}/npcAi/secrets`), {
      [mob.id]: { state: 'pending', reason: `${job.message.authorName}: "${job.message.text.slice(0, 120)}"`, at: Date.now() },
    }, { merge: true });
  }

  async runLine(job) {
    const now = Date.now();
    const last = this.lastLineByNpc.get(job.mobId) ?? 0;
    if (!job.direct && now - last < this.config.npcCooldownMs) return;
    const gap = this.config.globalGapMs - (now - this.lastNpcLineAt);
    if (gap > 0) await new Promise((r) => setTimeout(r, gap));

    const placement = this.placementFor(job.mobId, job.near);
    if (!placement) return; // NPC left the map or was muted
    // Nobody in the party knows the language it would answer in: they'd only see gibberish, so skip
    // the model and use a preset line (the DM still gets real lines when they talk to it). Beast, Plant
    // and Dead still ask the model, since everyone sees the body language it writes.
    const language = this.replyLanguage(placement.mob, job.heard);
    if (!job.fromDm && !hasGestureStyle(language) && !this.partyUnderstands(language)) {
      if (job.gated && Math.random() > 0.3) return; // only mutter now and then
      await this.postLine(placement.mob, placement, { text: presetLine(language), language, preset: true });
      return;
    }
    const tier = await this.prepare();
    if (!tier) return;
    const mob = await this.ensurePersonality(placement, tier);
    if (!mob) return;

    const transcript = this.transcript(mob, placement);
    if (job.gated) {
      const answer = await this.ask(tier, null, buildShouldSpeakPrompt({ mob, transcript, trigger: job.trigger }), { maxTokens: 4, temperature: 0 });
      if (!isYes(answer)) return;
    }

    const mapId = this.currentMapId;
    await this.writeStatus({ thinking: { mobId: mob.id, mapId, x: placement.x, y: placement.y, since: Date.now() } });
    const known = mobLanguageIds(mob);
    const gestureStyle = hasGestureStyle(language) ? language : undefined;
    let line = '';
    let gesture = '';
    try {
      const secretUnlocked = this.secrets[mob.id]?.state === 'unlocked';
      const system = buildSystemPrompt({
        mob, secretUnlocked, scene: this.scene(placement), memory: this.memoryFor(mob),
        speaking: this.languageName(language), knownLanguages: known.map((id) => this.languageName(id)), gesture: gestureStyle,
        realLanguage: REAL_LANGUAGES[language],
      });
      const raw = await this.ask(tier, system, buildLinePrompt({ mob, transcript, trigger: job.trigger }), { maxTokens: gestureStyle ? 110 : 80, temperature: 0.8 });
      if (gestureStyle) ({ text: line, gesture } = parseGestureLine(raw, mob.name));
      else line = cleanLine(raw, mob.name);
    } finally {
      await this.writeStatus({ thinking: null });
    }
    await this.postLine(mob, placement, { text: line, language, gesture, mapId });
  }

  /** Put an NPC line in the chat (unless NPCs were muted while it was being written). */
  async postLine(mob, placement, { text, language, gesture, preset = false, mapId = this.currentMapId }) {
    const muted = this.settings.mutedMobIds || [];
    if (!text || !this.live || !this.enabled || this.settings.mutedAll || muted.includes(mob.id) || muted.includes(mob.sourceMobId)) return;

    const id = `chat-${Date.now()}-${randomHex()}`;
    await setDoc(doc(this.db, `${this.path}/chatMessages/${id}`), {
      id,
      authorType: 'npc',
      authorId: mob.id,
      authorName: mob.name,
      text,
      language,
      ...(gesture ? { gesture } : {}),
      ...(preset ? { preset: true } : {}),
      createdAt: Date.now(),
      episodeId: this.showtime?.episodeId,
      mapId,
      x: placement.x,
      y: placement.y,
    });
    this.lastNpcLineAt = Date.now();
    this.lastLineByNpc.set(mob.id, Date.now());
    if (this.convos.has(mob.id)) this.noteConvo(mob);
    this.log(`[${this.name}] ${mob.name} (${preset ? 'preset' : this.activeModel ?? this.role}): ${text}`);
  }

  // ── status for the app ──

  async writeStatus(fields) {
    try {
      await setDoc(doc(this.db, `${this.path}/npcAi/status`), fields, { merge: true });
    } catch (err) {
      this.warn(`[${this.name}] status write failed:`, err.message);
    }
  }

  publishStatus() {
    if (!this.live) return;
    this.writeStatus({
      heartbeatAt: Date.now(),
      runner: this.role,
      activeModel: this.unloaded ? null : this.activeModel,
      note: this.enabled ? this.note : '',
      busy: this.busy,
    });
  }
}
